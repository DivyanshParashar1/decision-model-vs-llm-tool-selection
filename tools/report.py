"""Step 5 (runs on the Mac, light): compute every metric from the fetched prediction files and write
reports/tables.md + reports/results.json. RESULTS.md (the narrative) quotes these tables.

  python tools/report.py            # uses whatever prediction files exist under build/*/out

Instances are rebuilt locally from the MetaTool raw files and checked against docs/data_manifest.json,
so no large file has to be downloaded from Kaggle.
"""
import glob
import json
import pathlib
import re
import sys

import numpy as np
import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from tooldecide import evaluate as E  # noqa: E402
from tooldecide import instances as I  # noqa: E402
from tooldecide import metrics as M  # noqa: E402

SPLITS = ["test_seen", "test_unseen", "test_multi", "test_official", "val"]
SIZE_NAME = {1000: "1k", 4000: "4k"}


def size_name(n: int, n_full: int) -> str:
    return "full" if n == n_full else SIZE_NAME.get(n, str(n))


def load_instances() -> pd.DataFrame:
    cache = ROOT / "build" / "instances_local.parquet"
    man = json.load(open(ROOT / "docs" / "data_manifest.json"))
    if cache.exists():
        inst = pd.read_parquet(cache)
    else:
        inst, _, _ = I.build_all(*I.load_raw())
        inst.to_parquet(cache, index=False)
    assert I.split_hashes(inst) == man["split_hashes"], "local rebuild does not match the frozen manifest"
    return inst


def load_preds(n_full: int) -> dict[str, pd.DataFrame]:
    b = ROOT / "build"
    out = {}
    for name, f in [("C1 Qwen3-8B raw", "tools-02-baselines/out/preds_c1.parquet"),
                    ("C2 GLiNER raw", "tools-02-baselines/out/preds_c2.parquet")]:
        if (b / f).exists():
            out[name] = pd.read_parquet(b / f)
    for f in sorted(glob.glob(str(b / "tools-03-llm-star*/out/preds_llm_star_*.parquet"))):
        n = int(re.search(r"preds_llm_star_(\d+)\.parquet", f).group(1))
        if n >= 1000:  # skip QUICK smoke runs
            out[f"C3 Qwen3-8B QLoRA {size_name(n, n_full)}"] = pd.read_parquet(f)
    for f in sorted(glob.glob(str(b / "tools-04-dstar/out/preds_dstar_*.parquet"))):
        n, s = map(int, re.search(r"preds_dstar_(\d+)_s(\d+)\.parquet", f).groups())
        if n >= 1000:
            out[f"C4 GLiNER fine-tuned {size_name(n, n_full)} s{s}"] = pd.read_parquet(f)
    return out


def headline_metric(m: dict, split: str):
    return m.get("exact") if split == "test_multi" else m.get("acc")


def fmt_ci(m, ci):
    return "n/a" if m is None else f"{m:.3f} [{ci[0]:.3f}, {ci[1]:.3f}]"


def main():
    inst = load_instances()
    n_full = int((inst["split"] == "train").sum())
    preds = load_preds(n_full)
    scores = {k: E.score(inst, p) for k, p in preds.items()}
    lines = ["# Result tables (generated by tools/report.py)\n"]

    # headline: every config, accuracy (exact set for multi) with 95% bootstrap CI
    lines.append("## Accuracy by split (test_multi: exact two-tool set), 95% bootstrap CI\n")
    lines.append("| Config | " + " | ".join(SPLITS) + " |")
    lines.append("|---|" + "---|" * len(SPLITS))
    for k, r in scores.items():
        cells = []
        for s in SPLITS:
            m = r.get(s, {})
            key = "exact" if s == "test_multi" else "acc"
            cells.append(fmt_ci(m.get(key), m.get(f"{key}_ci", [np.nan, np.nan])) if m else "–")
        lines.append(f"| {k} | " + " | ".join(cells) + " |")

    # seed summary for D*
    seeds = {}
    for k, r in scores.items():
        mm = re.match(r"C4 GLiNER fine-tuned (\S+) s\d+", k)
        if mm:
            seeds.setdefault(mm.group(1), []).append(r)
    if seeds:
        lines.append("\n## D\\* (C4) mean ± sd over seeds\n")
        lines.append("| Size | seeds | " + " | ".join(SPLITS) + " |")
        lines.append("|---|---|" + "---|" * len(SPLITS))
        for size, rs in seeds.items():
            cells = []
            for s in SPLITS:
                v = [headline_metric(r[s], s) for r in rs if s in r]
                cells.append(f"{np.mean(v):.3f} ± {np.std(v, ddof=1) if len(v) > 1 else 0:.3f}" if v else "–")
            lines.append(f"| {size} | {len(rs)} | " + " | ".join(cells) + " |")

    # McNemar
    def pair(a, b):
        rows = []
        for s in ["test_seen", "test_unseen", "test_multi", "test_official"]:
            va, vb = E.correct_vector(inst, preds[a], s), E.correct_vector(inst, preds[b], s)
            idx = va.index.intersection(vb.index)
            rows.append((s, float(va[idx].mean()), float(vb[idx].mean()), M.mcnemar(va[idx], vb[idx]), len(idx)))
        return rows

    full_c3 = "C3 Qwen3-8B QLoRA full"
    c4_full = sorted(k for k in preds if k.startswith("C4 GLiNER fine-tuned full"))
    comparisons = [("C2 GLiNER raw", "C1 Qwen3-8B raw")]
    for c4 in c4_full:
        comparisons += [(c4, full_c3), (c4, "C1 Qwen3-8B raw")]
    comparisons = [(a, b) for a, b in comparisons if a in preds and b in preds]
    mcn = {}
    if comparisons:
        lines.append("\n## Paired McNemar tests (exact two-sided)\n")
        lines.append("| A | B | split | acc A | acc B | p | n |")
        lines.append("|---|---|---|---|---|---|---|")
        for a, b in comparisons:
            for s, x, y, p, n in pair(a, b):
                mcn[f"{a} vs {b} / {s}"] = dict(acc_a=x, acc_b=y, p=p, n=n)
                lines.append(f"| {a} | {b} | {s} | {x:.3f} | {y:.3f} | {p:.2g} | {n} |")

    # secondary metrics
    lines.append("\n## Secondary metrics (test_seen / test_unseen)\n")
    lines.append("| Config | macro acc seen | macro acc unseen | hard-distractor share of errors (seen) | "
                 "acc without name leak (seen) | ECE (seen) | acc at 90% coverage (seen) | set F1 multi | "
                 "official acc, query not in train | parse rate (seen) |")
    lines.append("|---|---|---|---|---|---|---|---|---|---|")
    for k, r in scores.items():
        se, un, mu, of = (r.get(s, {}) for s in ["test_seen", "test_unseen", "test_multi", "test_official"])
        f = lambda x: "–" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.3f}"  # noqa: E731
        lines.append(f"| {k} | {f(se.get('macro_acc'))} | {f(un.get('macro_acc'))} | {f(se.get('hard_confusion'))} | "
                     f"{f(se.get('acc_no_leak'))} | {f(se.get('ece'))} | {f(se.get('acc_at_90_coverage'))} | "
                     f"{f(mu.get('set_f1'))} | {f(of.get('acc_query_not_in_train'))} | {f(se.get('parse_rate'))} |")

    # costs
    costs = {}
    b = ROOT / "build"
    for f in sorted(glob.glob(str(b / "tools-03-llm-star*/out/cost_llm_star_*.json"))):
        c = json.load(open(f))
        if c.get("quick"):
            continue
        costs[f"C3 {size_name(c['n_train'], n_full)}"] = dict(
            train_gpu_h=c["train_seconds"] / 3600, gpus=1, trainable=c["trainable_params"], steps=c["steps"],
            peak_vram_gb=c["peak_vram_gb"], infer_ms_batched=c["inference"]["ms_per_decision_batched"],
            infer_hw="2× T4 (vLLM, TP=2)")
    cd = b / "tools-04-dstar/out/cost_dstar.json"
    if cd.exists():
        for tag, c in json.load(open(cd))["runs"].items():
            if c.get("train_rc") != 0 or c.get("n", 0) < 1000:
                continue
            costs[f"C4 {size_name(c['n'], n_full)} s{c['seed']}"] = dict(
                train_gpu_h=c["train_seconds"] / 3600, gpus=1, trainable=c["trainable_params"],
                peak_vram_gb=c["peak_vram_gb"], infer_ms_batched=c.get("inference", {}).get("ms_per_decision_batched"),
                latency_ms_median=c.get("inference", {}).get("latency_ms_median"), infer_hw="1× T4")
    tb = b / "tools-02-baselines/out"
    for k, f in [("C1", "preds_c1.parquet.timing.json"), ("C2", "preds_c2.parquet.timing.json")]:
        if (tb / f).exists():
            t = json.load(open(tb / f))
            costs[k] = dict(train_gpu_h=0, infer_ms_batched=t["ms_per_decision_batched"],
                            latency_ms_median=t.get("latency_ms_median"),
                            infer_hw="2× T4 (vLLM, TP=2)" if k == "C1" else "1× T4")
    if costs:
        lines.append("\n## Cost (T4 GPU-hours for training; inference per decision)\n")
        lines.append("| Run | train GPU-h | trainable params | peak VRAM GB | ms/decision batched | median ms unbatched | inference HW |")
        lines.append("|---|---|---|---|---|---|---|")
        for k, c in costs.items():
            g = lambda x, fmt: "–" if x is None else format(x, fmt)  # noqa: E731
            lines.append(f"| {k} | {c['train_gpu_h']:.2f} | {g(c.get('trainable'), ',')} | {g(c.get('peak_vram_gb'), '.1f')} | "
                         f"{g(c.get('infer_ms_batched'), '.0f')} | {g(c.get('latency_ms_median'), '.0f')} | {c['infer_hw']} |")

    out = ROOT / "reports"
    out.mkdir(exist_ok=True)
    (out / "tables.md").write_text("\n".join(lines) + "\n")
    json.dump(dict(scores=scores, mcnemar=mcn, costs=costs, configs=list(preds)), open(out / "results.json", "w"),
              indent=1, default=float)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
